ROOT=school.ROOT
ARTIFACT=ROOT/"ci-artifacts/progression-reactive-L-v2-pupil"
FIXTURE=ARTIFACT/"generic-witness.wbb"
PROJECT_TEXT=school.PROJECT_TEXT
REQUIRED=(
 "A5_PUPIL_HTML_LOADED","A5_PUPIL_JS_STARTED",
 "A5_PUPIL_SAME_WBB_REOPENED","A5_PUPIL_RUNTIME_READY",
 "A5_PUPIL_INTERPRETER_LANDED",
 "A5_PUPIL_NATIVE_ACHIEVED","A5_PUPIL_TEST_COMPLETE",
)
MARKER="# WEBEEBLOCKS_A5_V2_REAL_PUPIL_BROWSER_CI_ONLY"

class FixtureHandler(events.Handler):
    variant="A"
    wbb=""
    sha256=""
    def do_GET(self):
        if self.path!="/fixture":
            self.send_error(404)
            return
        data=json.dumps({"variant":self.variant,"wbb":self.wbb,
                         "sha256":self.sha256}).encode("utf-8")
        self.send_response(200)
        self.send_header("Content-Type","application/json; charset=utf-8")
        self.send_header("Content-Length",str(len(data)))
        self.end_headers()
        self.wfile.write(data)


def compose(variant):
    if not isinstance(variant,str) or variant not in "ABC" or len(variant)!=1:
        raise ValueError("unknown staged A5 variant")
    base=school.compose()
    old='window "reactive_l_v2_scene_ack_probe"'
    new='window "reactive_l_v2_pupil_probe"'
    if base.count(old)!=1 or base.count(school.MARKER)!=1:
        raise ValueError("missing exact original school-only source window")
    text=base.replace(old,new,1).replace(school.MARKER,MARKER,1)
    if (text.count(MARKER)!=1 or text.count(new)!=1 or
        text.count('controller "crazyflie_classroom_v2"')!=1 or
        'controller "crazyflie_runtime_v2"' in text or
        'WEBEEBLOCKS_REACTIVE_L_V2_A_SCENE' in text or
        'WEBEEBLOCKS_REACTIVE_L_V2_B_SCENE' in text or
        'WEBEEBLOCKS_REACTIVE_L_V2_C_SCENE' in text):
        raise ValueError("pupil world must begin empty with exact native school runtime")
    return text


def fixture_text():
    if not FIXTURE.is_file() or not (20<FIXTURE.stat().st_size<100000):
        raise FileNotFoundError("same genuine A5 .wbb fixture not generated by CI")
    text=FIXTURE.read_text(encoding="utf-8")
    doc=json.loads(text)
    if (doc.get("activity",{}).get("id")!="progression-reactive-L-v2" or
        any(token in text for token in
            ("reactive-L-a-v2","reactive-L-b-v2","reactive-L-c-v2"))):
        raise ValueError("A5 fixture contains variant token or wrong activity")
    return text,hashlib.sha256(text.encode("utf-8")).hexdigest()


def run(variant):
    text,sha=fixture_text()
    body=compose(variant)
    world=ROOT/f"worlds/ci_reactive_L_v2_pupil_{variant.lower()}.wbt"
    project=ROOT/f"worlds/.ci_reactive_L_v2_pupil_{variant.lower()}.wbproj"
    directory=ARTIFACT/variant
    directory.mkdir(parents=True,exist_ok=True)
    log=directory/"webots.log"
    if world.exists() or project.exists():
        raise FileExistsError("refuse overwrite of existing staged A5 pupil world")
    original_sha=hashlib.sha256(text.encode()).hexdigest()
    if sha!=original_sha:raise RuntimeError("A5 fixture changed during staging")
    events.EVENTS.clear()
    FixtureHandler.variant=variant
    FixtureHandler.wbb=text
    FixtureHandler.sha256=sha
    server=process=output=None
    try:
        for path in (
            ROOT/"controllers/crazyflie_classroom_v2/crazyflie_classroom_v2",
            ROOT/"controllers/progression_reactive_L_v2/progression_reactive_L_v2",
        ):
            if not path.is_file() or not path.stat().st_size:
                raise FileNotFoundError("missing independent compiled Webots controller "+str(path))
        world.write_text(body,encoding="utf-8")
        project.write_text(PROJECT_TEXT,encoding="utf-8")
        print("WEBEEBLOCKS_A5_PUPIL_NATIVE_WORLD_SHA256 variant="+variant+
              " sha256="+hashlib.sha256(body.encode()).hexdigest(),flush=True)
        server=events.http.server.ThreadingHTTPServer(
            ("127.0.0.1",8765),FixtureHandler)
        threading.Thread(target=server.serve_forever,daemon=True).start()
        env=dict(os.environ)
        env["WEBOTS_WEB_BROWSER"]="/workspace/tools/ci/webots_runtime_v2_browser.sh"
        output=log.open("w",encoding="utf-8")
        process=subprocess.Popen(
            ["timeout","-k","5s","360s","xvfb-run","-a","webots",
             "--stdout","--stderr","--batch","--mode=realtime",str(world)],
            cwd=ROOT,env=env,stdout=output,stderr=subprocess.STDOUT,
            start_new_session=True)
        deadline=time.monotonic()+345
        while time.monotonic()<deadline:
            names=[r.get("event") for r in events.EVENTS]
            if ("A5_PUPIL_ERROR" in names or process.poll() is not None):
                break
            if "A5_PUPIL_TEST_COMPLETE" in names:
                content=log.read_text(encoding="utf-8",errors="replace")
                match=(f"WEBEEBLOCKS_A5_V2_RESULT attempt=1 "
                       f"status=achieved stage={3 if variant in 'AB' else 4} variant={variant}")
                if match in content:
                    break
            time.sleep(.25)
    finally:
        if process and process.poll() is None:
            try:os.killpg(process.pid,signal.SIGTERM)
            except ProcessLookupError:pass
            try:process.wait(timeout=8)
            except subprocess.TimeoutExpired:
                try:os.killpg(process.pid,signal.SIGKILL)
                except ProcessLookupError:pass
                process.wait(timeout=8)
        if output:output.close()
        if server:server.shutdown();server.server_close()
        (directory/"events.json").write_text(
            json.dumps(events.EVENTS,indent=2,sort_keys=True)+"\n",encoding="utf-8")
        if world.exists():
            if world.read_text(encoding="utf-8")!=body:
                raise RuntimeError("refuse deletion of modified A5 browser world")
            world.unlink()
        if project.exists():
            if project.read_text(encoding="utf-8")!=PROJECT_TEXT:
                raise RuntimeError("refuse deletion of modified A5 project")
            project.unlink()
    native=log.read_text(encoding="utf-8",errors="replace")
    names=[r.get("event") for r in events.EVENTS]
    missing=[k for k in REQUIRED if names.count(k)!=1]
    ordered=not missing and [names.index(k) for k in REQUIRED]==sorted(
        names.index(k) for k in REQUIRED)
    marker=(f"WEBEEBLOCKS_A5_V2_RESULT attempt=1 status=achieved "
            f"stage={3 if variant in 'AB' else 4} variant={variant}")
    event=next((r.get("detail") for r in events.EVENTS
                if r.get("event")=="A5_PUPIL_TEST_COMPLETE"),None)
    wbb=next((r.get("detail") for r in events.EVENTS
              if r.get("event")=="A5_PUPIL_SAME_WBB_REOPENED"),None)
    failures=[x for x in ("WEBEEBLOCKS_A5_V2_FATAL",
                         "WEBEEBLOCKS_RUNTIME_V2 FATAL") if x in native]
    result=dict(variant=variant,fixture_sha256=sha,
                missing=missing,ordered=ordered,
                native_achieved=native.count(marker),
                error_events=names.count("A5_PUPIL_ERROR"),
                failures=failures,events=names,
                wbb_event=wbb,completion=event)
    result["pass"]=(
        not missing and ordered and not failures and
        result["native_achieved"]==1 and
        result["error_events"]==0 and
        isinstance(event,dict) and event.get("status")=="achieved" and
        event.get("wbb_sha256")==sha and
        isinstance(wbb,dict) and wbb.get("sha256")==sha and
        wbb.get("variant")==variant and
        wbb.get("loops")==2 and wbb.get("state_assignments")==1
    )
    (directory/"summary.json").write_text(
        json.dumps(result,indent=2,sort_keys=True)+"\n",encoding="utf-8")
    if not result["pass"]:
        print("FAIL A5 genuine pupil Blockly Webots "+json.dumps(result),
              file=sys.stderr)
        print(native[-11000:],file=sys.stderr)
        return 1
    print("PASS A5 real R2025a Blockly .wbb flight variant="+variant+
          " sha256="+sha+" native_independent_achieved=true",flush=True)
    return 0


if __name__=="__main__":
    parser=argparse.ArgumentParser()
